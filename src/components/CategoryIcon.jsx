// Static class maps so Tailwind can see every class.
export const TEXT_COLOR = {
  red: "text-cat-red",
  orange: "text-cat-orange",
  yellow: "text-cat-yellow",
  green: "text-cat-green",
  teal: "text-cat-teal",
  blue: "text-cat-blue",
  indigo: "text-cat-indigo",
  purple: "text-cat-purple",
  pink: "text-cat-pink",
  gray: "text-cat-gray",
};

export function iconLabel(slug) {
  const s = REGISTRY[slug] ? slug : LEGACY[slug];
  return s ? s.replace(/-/g, " ") : "custom";
}

/** Renders a stored icon slug (or a legacy emoji, mapped). `color` tints it. */
export function CategoryIcon({ icon, color, size = 20, className }) {
  const slug = REGISTRY[icon] ? icon : LEGACY[icon];
  const cls = cx(color && TEXT_COLOR[color], className);
  if (slug) {
    const Icon = REGISTRY[slug];
    return <Icon aria-hidden size={size} strokeWidth={2} className={cls} />;
  }
  return <Tag aria-hidden size={size} strokeWidth={2} className={cls} />;
}
